/**
 * Builds the WASM adapter and its private wasm-bindgen glue.
 *
 * `yarn build:wasm` writes `wasm/h3.wasm`, `lib/generated/h3.{js,d.ts}`, and `wasm/build-manifest.json`. `yarn
 * check:wasm-artifact` builds into a temporary directory and compares every output with the committed files, without
 * writing.
 *
 * The toolchain is pinned: Rust from `rust-toolchain.toml` and wasm-bindgen-cli `WASM_BINDGEN_VERSION`. A mismatched or
 * missing CLI fails with setup instructions instead of installing anything. No optimizer (wasm-opt) runs: the
 * correctness build is the release build.
 *
 * @license MIT
 * @author Teffen Ellis, et al.
 * @copyright Sister Software
 */

import { execFileSync } from "node:child_process"
import { createHash } from "node:crypto"
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

export const WASM_BINDGEN_VERSION = "0.2.130"
export const RUST_VERSION = "1.99.1"
const TARGET = "wasm32-unknown-unknown"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const check = process.argv.includes("--check")
const jobs = process.env.H3_BUILD_JOBS ?? "4"

function fail(message: string): never {
	console.error(`build:wasm: ${message}`)

	process.exit(1)
}

function run(cmd: string, args: string[], env: NodeJS.ProcessEnv = process.env): string {
	try {
		return execFileSync(cmd, args, { cwd: root, env, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] })
	} catch (error) {
		fail(`${cmd} ${args.join(" ")} failed: ${(error as Error).message}`)
	}
}

const rustc = run("rustc", ["--version"]).trim()

if (!rustc.startsWith(`rustc ${RUST_VERSION} `)) {
	fail(`expected rustc ${RUST_VERSION} (rust-toolchain.toml); found ${rustc}`)
}

let bindgen = ""

try {
	bindgen = execFileSync("wasm-bindgen", ["--version"], { encoding: "utf8" }).trim()
} catch {
	fail(
		`wasm-bindgen ${WASM_BINDGEN_VERSION} is not installed.\n` +
			`  Install it with: cargo install wasm-bindgen-cli --version ${WASM_BINDGEN_VERSION} --locked`
	)
}

if (bindgen !== `wasm-bindgen ${WASM_BINDGEN_VERSION}`) {
	fail(
		`expected wasm-bindgen ${WASM_BINDGEN_VERSION}; found "${bindgen}".\n` +
			`  Install it with: cargo install wasm-bindgen-cli --version ${WASM_BINDGEN_VERSION} --locked`
	)
}

// Remap host paths so panic locations embedded in the binary do not depend on checkout location.
const cargoHome = process.env.CARGO_HOME ?? join(process.env.HOME ?? "", ".cargo")
const rustflags = [`--remap-path-prefix=${root}=/h3`, `--remap-path-prefix=${cargoHome}=/cargo`, "-Cdebuginfo=0"]
const work = check ? mkdtempSync(join(tmpdir(), "h3-wasm-check-")) : join(root, "target")
const cargoTarget = check ? join(work, "cargo") : join(root, "target")

run(
	"cargo",
	[
		"build",
		"--locked",
		"--release",
		"-p",
		"sister-h3-wasm",
		"--target",
		TARGET,
		"-j",
		jobs,
		"--target-dir",
		cargoTarget,
	],
	{ ...process.env, CARGO_ENCODED_RUSTFLAGS: rustflags.join("\u001F"), RUSTFLAGS: undefined }
)

const bindgenOut = join(work, "wasm-bindgen")
rmSync(bindgenOut, { recursive: true, force: true })
mkdirSync(bindgenOut, { recursive: true })

run("wasm-bindgen", [
	"--target",
	"web",
	"--omit-default-module-path",
	"--out-dir",
	bindgenOut,
	"--out-name",
	"h3",
	join(cargoTarget, TARGET, "release", "sister_h3_wasm.wasm"),
])

const HEADER =
	"// @ts-nocheck\n// @generated by scripts/build-wasm.ts with wasm-bindgen " +
	WASM_BINDGEN_VERSION +
	". Private: import only from lib/runtime.\n"

const outputs: Record<string, Buffer> = {
	"wasm/h3.wasm": readFileSync(join(bindgenOut, "h3_bg.wasm")),
	"lib/generated/h3.js": Buffer.from(HEADER + readFileSync(join(bindgenOut, "h3.js"), "utf8")),
	"lib/generated/h3.d.ts": Buffer.from(
		"// @generated by scripts/build-wasm.ts. Private.\n" + readFileSync(join(bindgenOut, "h3.d.ts"), "utf8")
	),
}

// The binary embedded for synchronous first-use initialization in Node and browsers. The base64
// string is decoded only when the default entry first needs an instance.
const wasmBytes = outputs["wasm/h3.wasm"]!

outputs["lib/generated/h3-embedded.js"] = Buffer.from(
	`// @ts-nocheck
// @generated by scripts/build-wasm.ts from wasm/h3.wasm (${wasmBytes.length} bytes). Private.
const BASE64 = "${wasmBytes.toString("base64")}"

/** Decodes the embedded H3 WebAssembly binary. */
export function embeddedWasmBytes() {
	const text = atob(BASE64)
	const bytes = new Uint8Array(text.length)
	for (let i = 0; i < text.length; i++) bytes[i] = text.charCodeAt(i)
	return bytes
}
`
)

outputs["lib/generated/h3-embedded.d.ts"] = Buffer.from(
	"// @generated by scripts/build-wasm.ts. Private.\n/** Decodes the embedded H3 WebAssembly binary. */\nexport declare function embeddedWasmBytes(): Uint8Array<ArrayBuffer>\n"
)

const sha = (b: Buffer | string) => createHash("sha256").update(b).digest("hex")

const manifest = {
	sourceTreeSha256: sha(
		["Cargo.toml", "Cargo.lock", "rust-toolchain.toml", "crates/h3-wasm/Cargo.toml", "crates/h3-core/Cargo.toml"]
			.concat(
				run("git", [
					"ls-files",
					"--cached",
					"--others",
					"--exclude-standard",
					"crates/h3-core/src",
					"crates/h3-wasm/src",
				])
					.split("\n")
					.filter(Boolean)
					.toSorted()
			)
			.map((f) => `${f}\0${sha(readFileSync(join(root, f)))}`)
			.join("\n")
	),
	rustc,
	target: TARGET,
	profile: "release (Cargo.toml [profile.release])",
	// Host paths are recorded as placeholders so the manifest is identical on every host.
	rustflags: rustflags.map((f) => f.replace(root, "<checkout>").replace(cargoHome, "<cargo-home>")),
	wasmBindgen: WASM_BINDGEN_VERSION,
	// The portable libm the binary computes with (sister-h3's `libm` feature). Native builds with
	// the feature reproduce this binary's floats exactly only at the same version.
	libm:
		/\[\[package\]\]\nname = "libm"\nversion = "([^"]+)"/.exec(readFileSync(join(root, "Cargo.lock"), "utf8"))?.[1] ??
		"absent",
	wasmBindgenArgs: ["--target", "web", "--omit-default-module-path", "--out-name", "h3"],
	optimizer: "none",
	lockfiles: { "Cargo.lock": sha(readFileSync(join(root, "Cargo.lock"))) },
	outputs: Object.fromEntries(Object.entries(outputs).map(([k, v]) => [k, { sha256: sha(v), bytes: v.length }])),
}

const manifestText = JSON.stringify(manifest, null, "\t") + "\n"

if (check) {
	let ok = true

	for (const [file, bytes] of Object.entries(outputs)) {
		const path = join(root, file)

		if (!existsSync(path) || !readFileSync(path).equals(bytes)) {
			console.error(`check:wasm-artifact: ${file} differs from a fresh build (${sha(bytes)})`)

			ok = false
		}
	}

	const committed = existsSync(join(root, "wasm/build-manifest.json"))
		? readFileSync(join(root, "wasm/build-manifest.json"), "utf8")
		: ""

	if (committed !== manifestText) {
		console.error("check:wasm-artifact: wasm/build-manifest.json differs from a fresh build")

		ok = false
	}

	rmSync(work, { recursive: true, force: true })

	if (!ok) {
		process.exit(1)
	}

	console.log("check:wasm-artifact: committed artifacts match a fresh build")
} else {
	for (const [file, bytes] of Object.entries(outputs)) {
		mkdirSync(dirname(join(root, file)), { recursive: true })
		writeFileSync(join(root, file), bytes)
	}

	writeFileSync(join(root, "wasm/build-manifest.json"), manifestText)

	for (const [file, o] of Object.entries(manifest.outputs)) {
		console.log(`build:wasm: ${file} ${o.bytes} bytes ${o.sha256}`)
	}
}
