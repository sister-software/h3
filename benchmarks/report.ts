import { writeFileSync } from "node:fs"
import { join } from "node:path"

import { format } from "oxfmt"

import type { Stat } from "#benchmarks/stats"
import type { BenchmarkReport } from "#benchmarks/types"

import config from "../oxfmt.config.ts"

export function renderReport(report: BenchmarkReport): string {
	const {
		environment,
		samples,
		js,
		boundary,
		init: initStats,
		native,
		memory: { node: nodeMemory, worker },
	} = report

	const f = (x: number) => (x >= 100 ? x.toFixed(0) : x.toFixed(1))
	const iqr = (s: Stat) => `${f(s.p25)}–${f(s.p75)}`
	const mib = (b: unknown) => (typeof b === "number" ? (b / 2 ** 20).toFixed(2) : "n/a")

	return [
		"# Benchmark results",
		"",
		`Generated by \`yarn benchmark\` on ${environment.date}. ${environment.cpu}, ${environment.cores} cores, ${environment.memoryGiB} GiB; Node ${environment.node}; ${environment.rustc}; h3-js ${environment.h3js}; \`wasm/h3.wasm\` ${environment.wasmBytes} bytes. ${samples} interleaved samples per row after 3 warmup runs.`,
		"",
		`Load average before ${environment.loadAverageBefore.join(" / ")}, after ${report.environment.loadAverageAfter.join(" / ")} (1/5/15 min). **The machine is shared; with load above zero these numbers are indicative, not authoritative.**`,
		"",
		"## Public JavaScript API versus h3-js (Node)",
		"",
		"Measurement schema 2 times bulk API calls and result collection. Full output validation runs before warmup, outside timing. Results are not directly comparable with schema 1, which included joining strings, reductions, and formatting. Coordinate validation uses an absolute 1e-12 degree tolerance; index collections compare every value with ordering ignored where unspecified.",
		"",
		"| Function | This package ns/op (median, IQR) | h3-js ns/op (median, IQR) | Ratio | Validation |",
		"| --- | --- | --- | --- | --- |",
		...Object.entries(js).map(
			([k, v]) =>
				`| ${k} | ${f(v.ours.median)} (${iqr(v.ours)}) | ${f(v.h3js.median)} (${iqr(v.h3js)}) | ${(v.ours.median / v.h3js.median).toFixed(2)} | ${v.validation} |`
		),
		"",
		"Workloads: `latLngToCell` 10,000 seeded points at res 9; `cellToParent` those cells to res 5; `cellToLatLng` those cells; `gridDisk` k=2 on 1,000 of them (per call); `compactCells` all 2,401 res-9 children of one res-5 cell (per call); `polygonToCells` the C test San Francisco polygon at res 9 (per call).",
		"",
		"## Boundary costs (Node, ns/op median)",
		"",
		"| Step | ns/op |",
		"| --- | --- |",
		...Object.entries(boundary).map(([k, v]) => `| ${k} | ${f(v.median)} (${iqr(v)}) |`),
		"",
		`Cold start in fresh processes (median of ${initStats.importMs.samples}): import ${initStats.importMs.median.toFixed(2)} ms; with no \`init\`, the first call (which compiles and instantiates the embedded binary) ${initStats.firstCallMs.median.toFixed(2)} ms and the second ${(initStats.secondCallMs.median * 1000).toFixed(1)} µs. With the optional \`init({ bytes })\` preload: \`init\` ${initStats.explicitInitMs.median.toFixed(2)} ms, then the first call ${initStats.explicitFirstCallMs.median.toFixed(3)} ms.`,
		"",
		"## Native Rust versus C",
		"",
		"Rust is measured with the default platform libm and with the `libm` feature (the portable libm the WebAssembly build uses). Checksum comparison compares the default build with C; integer-only functions are unaffected by the feature.",
		"",
		"| Function | Rust ns/op (median, IQR) | Rust `libm` ns/op | C ns/op (median, IQR) | Ratio | `libm` ratio | Checksum match |",
		"| --- | --- | --- | --- | --- | --- | --- |",
		...Object.entries(native).map(
			([k, v]) =>
				`| ${k} | ${f(v.rust.median)} (${iqr(v.rust)}) | ${f(v.rustLibm.median)} (${iqr(v.rustLibm)}) | ${v.c ? `${f(v.c.median)} (${iqr(v.c)})` : "not run"} | ${v.c ? (v.rust.median / v.c.median).toFixed(2) : ""} | ${v.c ? (v.rustLibm.median / v.c.median).toFixed(2) : ""} | ${v.checksumMatch === undefined ? "" : v.checksumMatch ? "yes" : "no"} |`
		),
		"",
		"## Memory",
		"",
		"Node (fresh process, after two forced GCs; MiB):",
		"",
		"| Stage | JS heap used | ArrayBuffers | WASM memory |",
		"| --- | --- | --- | --- |",
		...Object.entries(nodeMemory.stages).map(
			([k, v]) => `| ${k} | ${mib(v.heapUsedBytes)} | ${mib(v.arrayBuffersBytes)} | ${mib(v.wasmMemoryBytes)} |`
		),
		"",
		`Repeated workload (5 rounds of 20 × gridDisk k=100, compactCells of ${nodeMemory.compactCellsInput} cells, polygonToCells res 10): WASM memory per round ${nodeMemory.repeatedWorkloadWasmBytes.map(mib).join(", ")} MiB.`,
		"",
		"Cloudflare workerd via `wrangler dev` (inspector `Runtime.getHeapUsage`; MiB):",
		"",
		...(worker.status !== "measured"
			? [`${worker.status}: ${worker.detail}`]
			: [
					"| Stage | JS heap used | Backing storage | WASM memory |",
					"| --- | --- | --- | --- |",
					...Object.entries(worker.stages).map(
						([k, v]) =>
							`| ${k} | ${mib(v.jsHeapUsedBytes)} | ${mib(v.backingStorageBytes)} | ${mib(v.wasmMemoryBytes)} |`
					),
					"",
					"`backingStorageSize` excludes WebAssembly memory, so WASM memory is reported separately.",
				]),
		"",
	].join("\n")
}

/**
 * Writes formatted reports even when the destination is outside the formatter's checked source tree.
 */
export async function writeReports(report: BenchmarkReport, directory: string): Promise<void> {
	const files = [
		["RESULTS.md", renderReport(report)],
		["results/latest.json", JSON.stringify(report)],
	] as const

	for (const [relative, contents] of files) {
		const path = join(directory, relative)
		const result = await format(path, contents, config)

		if (result.errors.length) throw new Error(JSON.stringify(result.errors))
		writeFileSync(path, result.code)
	}
}
