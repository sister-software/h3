//! Shared fixture loading for C parity tests.

#![allow(dead_code)]

use serde_json::Value;
use std::path::PathBuf;

pub struct Record {
    pub args: Value,
    pub error: u32,
    pub result: Value,
    pub line: usize,
}

pub fn load(operation: &str) -> Vec<Record> {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures").join(format!("{operation}.jsonl"));
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("reading {}: {e}", path.display()));
    let records: Vec<Record> = text
        .lines()
        .enumerate()
        .map(|(i, l)| {
            let v: Value = serde_json::from_str(l).unwrap();
            assert_eq!(v["schemaVersion"], 1);
            assert_eq!(v["operation"], operation);
            Record {
                args: v["args"].clone(),
                error: v["error"].as_u64().unwrap() as u32,
                result: v["result"].clone(),
                line: i + 1,
            }
        })
        .collect();
    assert!(!records.is_empty(), "{operation}: no fixture records");
    records
}

pub fn idx(v: &Value) -> u64 {
    u64::from_str_radix(v.as_str().unwrap(), 16).unwrap()
}

pub fn idxs(v: &Value) -> Vec<u64> {
    v.as_array().unwrap().iter().map(idx).collect()
}

pub fn f(v: &Value) -> f64 {
    match v {
        Value::String(s) => match s.as_str() {
            "nan" => f64::NAN,
            "inf" => f64::INFINITY,
            "-inf" => f64::NEG_INFINITY,
            _ => panic!("bad float tag {s}"),
        },
        _ => v.as_f64().unwrap(),
    }
}

pub fn i(v: &Value) -> i64 {
    v.as_i64().unwrap()
}

pub fn err<T>(r: Result<T, sister_h3::H3Error>) -> (u32, Option<T>) {
    match r {
        Ok(v) => (0, Some(v)),
        Err(e) => (e.code(), None),
    }
}

/// Tracks the maximum absolute floating-point difference for reporting.
#[derive(Default)]
pub struct MaxErr {
    pub max: f64,
    pub count: usize,
}

impl MaxErr {
    pub fn check(&mut self, got: f64, want: f64, tol: f64, ctx: &str) {
        let d = (got - want).abs();
        self.count += 1;
        if d > self.max {
            self.max = d;
        }
        assert!(d <= tol, "{ctx}: got {got:e}, want {want:e}, |diff| {d:e} > {tol:e}");
    }
}

// ---------------------------------------------------------------------------------------------
// Floating-point comparison (docs/api-decisions.md, "Comparison rules").
//
// The fixtures were generated by C on linux x86-64 with glibc. A native build on that platform
// with the default (platform libm) math reproduces them bit for bit, so there the comparison is
// exact. Everywhere else (macOS, Windows, musl, aarch64 glibc, or the `libm` feature) the
// transcendental functions differ in the last bits, and results are compared within the same
// absolute bounds the JavaScript suite uses for WASM. Values computed without libm calls (unit
// conversions, the average tables) are compared exactly on every platform by the callers.

/// Whether this build reproduces the committed fixtures bit for bit.
pub const EXACT: bool =
    cfg!(all(target_os = "linux", target_env = "gnu", target_arch = "x86_64", not(feature = "libm")));

/// 1e-12 degrees, in radians (test/shared/fixture-cases.ts `COORD_TOLERANCE_DEGREES`).
pub const COORD_TOL_RADS: f64 = 1e-12 * std::f64::consts::PI / 180.0;
/// Radian units (`LENGTH_TOLERANCE_RADS`).
pub const LENGTH_TOL_RADS: f64 = 1e-13;
/// Per sqrt(rads²) (`AREA_TOLERANCE_PER_SQRT_RADS2`).
pub const AREA_TOL_PER_SQRT_RADS2: f64 = 1e-14;
/// The C library's Earth radius.
pub const EARTH_RADIUS_KM: f64 = 6371.007180918475;

/// The physical kind of a floating-point result, which selects its tolerance.
#[derive(Clone, Copy, Debug)]
pub enum Kind {
    /// A latitude or longitude in radians.
    Coord,
    /// A length in `scale` units per radian (1 for radians, the Earth radius for km or m).
    Length { scale: f64 },
    /// An area in `scale` units per rad² (1 for rads², R² for km² or m²).
    Area { scale: f64 },
}

impl Kind {
    /// The kind for an operation named like `cellAreaKm2` or `edgeLengthM`.
    pub fn for_op(op: &str) -> Kind {
        let r_km = EARTH_RADIUS_KM;
        if op.contains("Area") {
            let scale = if op.ends_with("Km2") {
                r_km * r_km
            } else if op.ends_with("M2") {
                (r_km * 1000.0) * (r_km * 1000.0)
            } else {
                1.0
            };
            Kind::Area { scale }
        } else {
            let scale = if op.ends_with("Km") {
                r_km
            } else if op.ends_with('M') {
                r_km * 1000.0
            } else {
                1.0
            };
            Kind::Length { scale }
        }
    }

    fn tolerance(self, want: f64) -> f64 {
        match self {
            Kind::Coord => COORD_TOL_RADS,
            Kind::Length { scale } => LENGTH_TOL_RADS * scale,
            Kind::Area { scale } => AREA_TOL_PER_SQRT_RADS2 * (want.abs() / scale).sqrt() * scale,
        }
    }
}

/// Compare one floating-point result; returns the difference in tolerance units for reporting.
pub fn float_matches(got: f64, want: f64, kind: Kind) -> Result<f64, String> {
    if got.to_bits() == want.to_bits() || (got.is_nan() && want.is_nan()) {
        return Ok(0.0);
    }
    if EXACT || !got.is_finite() || !want.is_finite() {
        return Err(format!("got {got:e}, want {want:e} (exact comparison)"));
    }
    let tol = kind.tolerance(want);
    let d = (got - want).abs();
    if d <= tol { Ok(d / tol) } else { Err(format!("got {got:e}, want {want:e}, |diff| {d:e} > {tol:e}")) }
}

/// Assert one floating-point result, tracking the worst difference relative to its tolerance.
pub fn check_float(worst: &mut f64, got: f64, want: f64, kind: Kind, ctx: &str) {
    match float_matches(got, want, kind) {
        Ok(r) => *worst = worst.max(r),
        Err(e) => panic!("{ctx}: {e}"),
    }
}

/// One-line report of how a suite compared floats, printed with `--nocapture`.
pub fn report(what: &str, worst: f64) {
    if EXACT {
        println!("{what}: bit-exact (reference platform)");
    } else {
        println!("{what}: worst difference {worst:.3} of tolerance (non-reference math)");
    }
}
